const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = path.join(__dirname, '../Grocery/js/store.js');
assert.ok(fs.existsSync(source), 'Assignment 4 product and cart logic must exist');
const context = { window: {}, Date, Math, Intl };
vm.createContext(context);
vm.runInContext(fs.readFileSync(source, 'utf8'), context);
const s = context.window.Lido;
assert.equal(s.products.length, 8);
assert.ok(s.products.every(p => Object.keys(p).length >= 4));
assert.equal(s.findProduct('milk').price, 846);
assert.equal(s.findProduct('missing'), undefined);
assert.equal(s.filterProducts(s.products, 'MILK', 'dairy').length, 1);
assert.equal(s.filterProducts(s.products, 'milk', 'meat').length, 0);
assert.equal(s.filterProducts(s.products, '   ', 'all').length, 8);
assert.equal(s.validQuantity('2'), true);
for (const value of ['', '1.5', '0', '-1', '1000', 'NaN', Infinity]) assert.equal(s.validQuantity(value), false);
for (const value of [true, false, null, undefined, [], {}]) assert.equal(s.validQuantity(value), false);
let cart = s.addItem([], 'milk');
cart = s.addItem(cart, 'bread');
assert.equal(s.cartTotals(cart).total, 1076);
assert.equal(s.cartTotals(cart).quantity, 2);
assert.equal(s.cartTotals(s.changeQuantity(cart, 'milk', 2)).total, 1922);
assert.equal(s.changeQuantity(cart, 'milk', 0).length, 1);
assert.equal(s.changeQuantity(cart, 'missing', 3).length, 2);
assert.equal(s.changeQuantity(cart, 'milk', 1000)[0].quantity, 1);
assert.equal(s.normalizeCart(null).length, 0);
assert.equal(s.normalizeCart([{id:'missing',quantity:1},{id:'milk',quantity:-1}]).length, 0);
assert.equal(s.normalizeCart([{id:'milk',quantity:2},{id:'milk',quantity:3}])[0].quantity, 5);
assert.equal(s.normalizeCart([{id:'milk',quantity:999},{id:'milk',quantity:2}])[0].quantity, 999);
assert.equal(s.cartTotals(s.addItem([{id:'milk',quantity:999}], 'milk')).quantity, 999);
assert.match(s.makeReference(), /^DEMO-\d{6}$/);
const request = {name:'Temirlan', email:'test@example.com', phone:'', product:'Milk', quantity:'2', date:'2026-10-18', category:'dairy', method:'email', permission:true, comment:''};
assert.equal(Object.keys(s.validateRequest(request,'2026-10-18')).length, 0);
assert.ok(s.validateRequest({...request,name:'  '},'2026-10-18').name);
assert.ok(s.validateRequest({...request,email:'bad'},'2026-10-18').email);
assert.ok(s.validateRequest({...request,method:'phone'},'2026-10-18').phone);
assert.ok(s.validateRequest({...request,quantity:'1.5'},'2026-10-18').quantity);
assert.ok(s.validateRequest({...request,date:'2026-10-17'},'2026-10-18').date);
assert.ok(s.validateRequest({...request,category:'fake'},'2026-10-18').category);
assert.ok(s.validateRequest({...request,permission:false},'2026-10-18').permission);
assert.ok(s.validateRequest({...request,comment:'a'.repeat(1001)},'2026-10-18').comment);
assert.ok(s.validateRequest({...request,date:'2026-02-30'},'2026-02-01').date);
assert.equal(Object.keys(s.validateRequest({...request,date:'',method:'phone',phone:'+7 700 000 00 00'},'2026-10-18')).length, 0);
assert.ok(s.validateRequest({...request,phone:'call me'},'2026-10-18').phone);
assert.ok(s.validateRequest({...request,method:'unknown'},'2026-10-18').method);
console.log('PASS: product data, connected filters, cart arithmetic/bounds/normalization, demo reference and request validation.');
